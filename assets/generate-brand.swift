    <title id="title">FireLink</title>
    <path fill="#F3F3FA" d="M0 0h108v108H0z"/>
    <path fill="#1A1B20" d="\(path)"/>
  </svg>
  """
try write(svg, to: "assets/firelink.svg")
try write(svg, to: "presentation/proposal/public/firelink.svg")
