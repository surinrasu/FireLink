// Run from the repository root: xcrun swift assets/generate-brand.swift
// Keep the web, Apple, and Android assets on the same FireLink wordmark.
import AppKit
import CoreText

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let font = NSFont(name: "PingFangSC-Semibold", size: 28)!
let line = CTLineCreateWithAttributedString(
  NSAttributedString(string: "FireLink", attributes: [.font: font, .kern: -1.12]))
let lettering = CGMutablePath()
for run in CTLineGetGlyphRuns(line) as! [CTRun] {
  let count = CTRunGetGlyphCount(run)
  var glyphs = [CGGlyph](repeating: 0, count: count)
  var positions = [CGPoint](repeating: .zero, count: count)
  CTRunGetGlyphs(run, CFRange(location: 0, length: 0), &glyphs)
  CTRunGetPositions(run, CFRange(location: 0, length: 0), &positions)
  let runFont = (CTRunGetAttributes(run) as NSDictionary)[kCTFontAttributeName] as! CTFont
  for index in 0..<count {
    if let glyph = CTFontCreatePathForGlyph(runFont, glyphs[index], nil) {
      lettering.addPath(
        glyph, transform: CGAffineTransform(translationX: positions[index].x, y: positions[index].y)
      )
    }
  }
}
let bounds = lettering.boundingBoxOfPath
let scale = 88 / bounds.width
var transform = CGAffineTransform(
  a: scale, b: 0, c: 0, d: -scale,
  tx: 10 - bounds.minX * scale, ty: 54 + bounds.midY * scale)
let wordmark = lettering.copy(using: &transform)!
func point(_ p: CGPoint) -> String {
  String(format: "%.3f,%.3f", locale: Locale(identifier: "en_US_POSIX"), Double(p.x), Double(p.y))
}
var path = ""
wordmark.applyWithBlock { pointer in
  let element = pointer.pointee
  switch element.type {
  case .moveToPoint: path += "M\(point(element.points[0]))"
  case .addLineToPoint: path += "L\(point(element.points[0]))"
  case .addQuadCurveToPoint: path += "Q\(point(element.points[0])) \(point(element.points[1]))"
  case .addCurveToPoint:
    path += "C\(point(element.points[0])) \(point(element.points[1])) \(point(element.points[2]))"
  case .closeSubpath: path += "Z"
  @unknown default: fatalError("Unsupported glyph path")
  }
}
func write(_ content: String, to relativePath: String) throws {
  try (content + "\n").write(
    to: root.appendingPathComponent(relativePath), atomically: true, encoding: .utf8)
}
