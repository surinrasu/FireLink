    <path android:fillColor="#FFFFFF" android:pathData="\(path)"/>
  </vector>
  """, to: "android/app/src/main/res/drawable/ic_firelink_notification.xml")

let size = 1024
let colorSpace = CGColorSpace(name: CGColorSpace.sRGB)!
func color(_ red: CGFloat, _ green: CGFloat, _ blue: CGFloat) -> CGColor {
  CGColor(colorSpace: colorSpace, components: [red / 255, green / 255, blue / 255, 1])!
}
let context = CGContext(
  data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: size * 4,
  space: colorSpace, bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
context.setFillColor(color(243, 243, 250))
context.fill(CGRect(x: 0, y: 0, width: size, height: size))
context.translateBy(x: 0, y: CGFloat(size))
context.scaleBy(x: CGFloat(size) / 108, y: -CGFloat(size) / 108)
context.setFillColor(color(26, 27, 32))
context.addPath(wordmark)
context.fillPath()
let png = NSBitmapImageRep(cgImage: context.makeImage()!).representation(
  using: .png, properties: [:])!
try png.write(
  to: root.appendingPathComponent("apple/FireLink/Assets.xcassets/AppIcon.appiconset/AppIcon.png"))
print("Generated FireLink wordmark assets for web, Apple, and Android.")

// Native Mac and Vision Pro targets require their own asset catalog icon types.
let catalog = root.appendingPathComponent("apple/FireLink/Assets.xcassets")
let info: [String: Any] = ["author": "xcode", "version": 1]
func writeJSON(_ value: [String: Any], at url: URL) throws {
  try FileManager.default.createDirectory(
    at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
  try JSONSerialization.data(withJSONObject: value, options: [.prettyPrinted, .sortedKeys])
    .write(to: url)
}
func renderIcon(pixels: Int, background: Bool, foreground: Bool, to url: URL) throws {
  let bitmap = CGContext(
    data: nil, width: pixels, height: pixels, bitsPerComponent: 8, bytesPerRow: pixels * 4,
    space: colorSpace, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
  if background {
    bitmap.setFillColor(color(243, 243, 250))
    bitmap.fill(CGRect(x: 0, y: 0, width: pixels, height: pixels))
  }
  if foreground {
    bitmap.translateBy(x: 0, y: CGFloat(pixels))
    bitmap.scaleBy(x: CGFloat(pixels) / 108, y: -CGFloat(pixels) / 108)
    bitmap.setFillColor(color(26, 27, 32))
    bitmap.addPath(wordmark)
    bitmap.fillPath()
  }
  try NSBitmapImageRep(cgImage: bitmap.makeImage()!).representation(using: .png, properties: [:])!
    .write(to: url)
}

let macIcon = catalog.appendingPathComponent("MacAppIcon.appiconset")
var macImages: [[String: String]] = []
for points in [16, 32, 128, 256, 512] {
  for scale in [1, 2] {
    let filename = "icon-\(points)@\(scale)x.png"
    macImages.append([
      "idiom": "mac", "size": "\(points)x\(points)", "scale": "\(scale)x", "filename": filename,
    ])
  }
}
try writeJSON(["info": info, "images": macImages], at: macIcon.appendingPathComponent("Contents.json"))
for points in [16, 32, 128, 256, 512] {
  for scale in [1, 2] {
    try renderIcon(
      pixels: points * scale, background: true, foreground: true,
      to: macIcon.appendingPathComponent("icon-\(points)@\(scale)x.png"))
  }
}

let visionIcon = catalog.appendingPathComponent("VisionAppIcon.solidimagestack")
try writeJSON([
  "info": info,
  "layers": [["filename": "Front.solidimagestacklayer"], ["filename": "Back.solidimagestacklayer"]],
], at: visionIcon.appendingPathComponent("Contents.json"))
for layerName in ["Front", "Back"] {
  let layer = visionIcon.appendingPathComponent("\(layerName).solidimagestacklayer")
  try writeJSON(["info": info], at: layer.appendingPathComponent("Contents.json"))
  let content = layer.appendingPathComponent("Content.imageset")
  try writeJSON([
    "info": info, "images": [["idiom": "vision", "scale": "2x", "filename": "Icon.png"]],
  ], at: content.appendingPathComponent("Contents.json"))
  try renderIcon(
    pixels: 1024, background: layerName == "Back", foreground: layerName == "Front",
    to: content.appendingPathComponent("Icon.png"))
}
print("Generated native Mac and layered Vision Pro icons.")
